# ======================================================================
# ABSTRACT BASE
# ======================================================================

class AIProvider(ABC):
    """The base contract for any LLM acting as a Cloud Security Analyst."""

    name: str = "base"

    @abstractmethod
    def health_check(self) -> bool:
        """Verifies if the AI provider is authenticated and accessible."""
        pass

    @abstractmethod
    def analyze_finding(self, finding: Finding) -> Optional[str]:
        pass

    @abstractmethod
    def generate_executive_summary(self, summary: AssessmentSummary) -> Optional[str]:
        pass

    def resolve_cli_error(self, error_msg: str) -> Optional[str]:
        """Default error-resolution path shared by every provider that
        can do free-form text generation. Providers may override this."""
        raise NotImplementedError


# ======================================================================
# SHELL-GPT PROVIDER (local `sgpt` CLI — no code-level API key needed,
# sgpt manages its own key/config independently)
# ======================================================================

class ShellGPTProvider(AIProvider):
    name = "shellgpt"

    def __init__(self):
        if not self.health_check():
            raise ToolMissingError(
                "Shell-GPT (sgpt) is not installed or not in PATH. "
                "Install it using: pip install shell-gpt"
            )

    def health_check(self) -> bool:
        try:
            result = subprocess.run(["sgpt", "--version"], capture_output=True, text=True, check=True)
            return "sgpt" in result.stdout.lower() or result.returncode == 0
        except (subprocess.CalledProcessError, FileNotFoundError):
            return False

    def analyze_finding(self, finding: Finding) -> Optional[str]:
        prompt = FINDING_ANALYSIS_PROMPT.format(finding_json=finding.model_dump_json(indent=2))
        return self._call_sgpt(prompt)

    def generate_executive_summary(self, summary: AssessmentSummary) -> Optional[str]:
        metrics_json = summary.model_dump_json(exclude={"findings"}, indent=2)
        prompt = EXECUTIVE_SUMMARY_PROMPT.format(summary_json=metrics_json)
        return self._call_sgpt(prompt)

    def resolve_cli_error(self, error_msg: str) -> Optional[str]:
        log.info("[cyan]Asking Shell-GPT for an error resolution...[/cyan]")
        prompt = ERROR_RESOLUTION_PROMPT.format(error_msg=error_msg)
        return self._call_sgpt(prompt)

    def _call_sgpt(self, prompt: str) -> Optional[str]:
        cmd = ["sgpt", "--no-cache", prompt]
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
            if result.returncode != 0:
                log.error(f"Shell-GPT returned an error: {result.stderr.strip()}")
                return None
            return result.stdout.strip()
        except subprocess.TimeoutExpired:
            log.warning("Shell-GPT request timed out after 60 seconds.")
            return None
        except Exception as e:
            log.error(f"Failed to communicate with Shell-GPT: {str(e)}")
            return None


# ======================================================================
# OPENAI PROVIDER (direct HTTPS call — no heavy SDK dependency)
# ======================================================================

class OpenAIProvider(AIProvider):
    name = "openai"

    def __init__(self):
        if requests is None:
            raise AIProviderError("The 'requests' package is not installed. Run: pip install -r requirement.txt")
        self.api_key = settings.get_ai_api_key("openai")
        self.model = settings.ai.openai_model
        if not self.health_check():
            raise AIProviderError("OpenAI API Key is missing or invalid (check OPENAI_API_KEY in .env).")

    def health_check(self) -> bool:
        return bool(self.api_key and self.api_key.startswith("sk-"))

    def analyze_finding(self, finding: Finding) -> Optional[str]:
        prompt = FINDING_ANALYSIS_PROMPT.format(finding_json=finding.model_dump_json(indent=2))
        return self._call_api(prompt, system_role="You are a Principal Cloud Security Engineer.")

    def generate_executive_summary(self, summary: AssessmentSummary) -> Optional[str]:
        metrics_json = summary.model_dump_json(exclude={"findings"}, indent=2)
        prompt = EXECUTIVE_SUMMARY_PROMPT.format(summary_json=metrics_json)
        return self._call_api(prompt, system_role="You are a vCISO.")

    def resolve_cli_error(self, error_msg: str) -> Optional[str]:
        prompt = ERROR_RESOLUTION_PROMPT.format(error_msg=error_msg)
        return self._call_api(prompt, system_role="You are a calm, precise DevOps troubleshooting assistant.")

    def _call_api(self, prompt: str, system_role: str) -> Optional[str]:
        headers = {"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"}
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_role},
                {"role": "user", "content": prompt},
            ],
            # Keep it small/cheap for free or limited-token tiers.
            "max_tokens": 500,
            "temperature": 0.2,
        }
        try:
            log.debug(f"Sending request to OpenAI API (model={self.model})...")
            response = requests.post(
                "https://api.openai.com/v1/chat/completions",
                headers=headers, json=payload, timeout=30,
            )
            response.raise_for_status()
            data = response.json()
            return data["choices"][0]["message"]["content"].strip()
        except requests.exceptions.RequestException as e:
            log.error(f"OpenAI API request failed: {str(e)}")
            return None


# ======================================================================
# ANTHROPIC / CLAUDE PROVIDER (direct HTTPS call to the Messages API)
# ======================================================================

class AnthropicProvider(AIProvider):
    """Talks to Claude directly via the Anthropic Messages API.
    Uses a small/cheap default model so a free or limited-token key
    goes as far as possible."""

    name = "anthropic"
    API_URL = "https://api.anthropic.com/v1/messages"
    API_VERSION = "2023-06-01"

    def __init__(self):
        if requests is None:
            raise AIProviderError("The 'requests' package is not installed. Run: pip install -r requirement.txt")
        self.api_key = settings.get_ai_api_key("anthropic")
        self.model = settings.ai.anthropic_model
        if not self.health_check():
            raise AIProviderError("Anthropic API Key is missing or invalid (check ANTHROPIC_API_KEY in .env).")

    def health_check(self) -> bool:
        return bool(self.api_key and self.api_key.startswith("sk-ant-"))

    def analyze_finding(self, finding: Finding) -> Optional[str]:
        prompt = FINDING_ANALYSIS_PROMPT.format(finding_json=finding.model_dump_json(indent=2))
        return self._call_api(prompt, system_role="You are a Principal Cloud Security Engineer.")

    def generate_executive_summary(self, summary: AssessmentSummary) -> Optional[str]:
        metrics_json = summary.model_dump_json(exclude={"findings"}, indent=2)
        prompt = EXECUTIVE_SUMMARY_PROMPT.format(summary_json=metrics_json)
        return self._call_api(prompt, system_role="You are a vCISO.")

    def resolve_cli_error(self, error_msg: str) -> Optional[str]:
        prompt = ERROR_RESOLUTION_PROMPT.format(error_msg=error_msg)
        return self._call_api(prompt, system_role="You are a calm, precise DevOps troubleshooting assistant.")

    def _call_api(self, prompt: str, system_role: str) -> Optional[str]:
        headers = {
            "x-api-key": self.api_key,
            "anthropic-version": self.API_VERSION,
            "content-type": "application/json",
        }
        payload = {
            "model": self.model,
            "max_tokens": 500,
            "system": system_role,
            "messages": [{"role": "user", "content": prompt}],
        }
        try:
            log.debug(f"Sending request to Anthropic API (model={self.model})...")
            response = requests.post(self.API_URL, headers=headers, json=payload, timeout=30)
            response.raise_for_status()
            data = response.json()
            parts = data.get("content", [])
            text = "".join(p.get("text", "") for p in parts if p.get("type") == "text")
            return text.strip() or None
        except requests.exceptions.RequestException as e:
            log.error(f"Anthropic API request failed: {str(e)}")
            return None


