"""
InternShield CSCC — AI Engine
==============================
File 3 of 5.

This is the "heavy duty, durable" AI layer. It merges what used to be
base.py + openai_provider.py + shellgpt.py + prompts/templates.py +
the ai/__init__.py factory, and adds two brand-new pieces that make
the whole tool resilient even on a free/limited-token API tier:

    1. AnthropicProvider  — talks to the Claude API directly (Messages
                             endpoint), using a small/cheap model by
                             default so a free-tier key's token budget
                             lasts as long as possible.
    2. OfflineAdvisor      — a zero-cost, zero-network, rule-based
                             fallback. If NO API key and NO shell-gpt
                             are available, the tool still produces
                             useful advisory text instead of crashing
                             or silently doing nothing.

IMPORTANT — ABOUT API KEYS:
    No real API key is (or should ever be) hardcoded in this file or
    anywhere in this repo. You supply your own key(s) in `.env`
    (copied from `.env.example`). This is standard practice — a key
    baked into source code is a leaked key the moment the repo is
    pushed to GitHub. `.env` is already git-ignored for you.

The `AIProviderFactory` / `resolve_error()` helpers implement a
FALLBACK CHAIN:  shellgpt -> openai -> anthropic -> offline
so a single missing tool or expired key never takes the whole
feature down — it just degrades gracefully to the next option.
"""

