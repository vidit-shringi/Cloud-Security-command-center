# OFFLINE ADVISOR — zero network, zero API key, always available.
# This is what makes the tool durable: it NEVER hard-fails just
# because the internet or a key isn't there.
# ======================================================================

class OfflineAdvisor(AIProvider):
    name = "offline"

    _KNOWLEDGE_BASE = [
        ("no such file", "The file/path referenced doesn't exist. Check the path and current working directory (`pwd`, `ls`)."),
        ("permission denied", "The current user lacks OS-level permission. Try `chmod +x <file>` for scripts, or re-run with the correct user (avoid `sudo` unless truly required)."),
        ("modulenotfounderror", "A Python package is missing. Activate your virtual environment and run: pip install -r requirement.txt"),
        ("no module named", "A Python package is missing. Activate your virtual environment and run: pip install -r requirement.txt"),
        ("nocredentialserror", "AWS credentials were not found. Run `aws configure` or set AWS_ACCESS_KEY_ID / AWS_SECRET_ACCESS_KEY in your .env."),
        ("accessdenied", "Your AWS identity lacks the IAM permission for this API call. Attach a read-only policy such as `SecurityAudit` or `ReadOnlyAccess`."),
        ("trivy", "Trivy isn't installed or not on PATH. Install it: https://aquasecurity.github.io/trivy/latest/getting-started/installation/"),
        ("sgpt", "Shell-GPT isn't installed or configured. Run: pip install shell-gpt && sgpt --install-integration"),
        ("api key", "An AI API key is missing or invalid. Copy .env.example to .env and set OPENAI_API_KEY or ANTHROPIC_API_KEY."),
        ("timeout", "The request took too long — check your network connection, or the remote service may be rate-limiting you. Try again shortly."),
        ("connectionerror", "Could not reach the network/API endpoint. Check your internet connection or firewall/proxy settings."),
        ("yaml", "config.yaml has a syntax error. Compare it against config.example.yaml and fix the indentation/keys."),
        ("json", "A response could not be parsed as valid JSON — the upstream tool may have printed an unexpected message alongside its output."),
    ]

    def health_check(self) -> bool:
        return True  # Always available — no external dependency at all.

    def analyze_finding(self, finding: Finding) -> Optional[str]:
        return (
            f"[Offline mode — no AI key/tool configured]\n"
            f"Risk: {finding.impact}\n"
            f"Suggested fix: {finding.recommendation}\n"
            f"(Set OPENAI_API_KEY, ANTHROPIC_API_KEY, or install shell-gpt for deeper AI analysis.)"
        )

    def generate_executive_summary(self, summary: AssessmentSummary) -> Optional[str]:
        return (
            f"[Offline mode — no AI key/tool configured]\n"
            f"This assessment of '{summary.target_environment}' produced {summary.total_findings} findings: "
            f"{summary.critical_count} Critical, {summary.high_count} High, {summary.medium_count} Medium, "
            f"{summary.low_count} Low. Prioritize Critical and High findings first — they represent the "
            f"highest-likelihood paths to compromise or data exposure."
        )

    def resolve_cli_error(self, error_msg: str) -> Optional[str]:
        lowered = error_msg.lower()
        for keyword, advice in self._KNOWLEDGE_BASE:
            if keyword in lowered:
                return (
                    f"[Offline error-resolver — matched pattern: '{keyword}']\n"
                    f"{advice}\n\n"
                    f"Raw error: {error_msg.strip()[:300]}"
                )
        return (
            "[Offline error-resolver — no exact pattern matched]\n"
            "General checklist: (1) is the virtual environment activated? "
            "(2) did `pip install -r requirement.txt` complete successfully? "
            "(3) check logs/errors.log for the full traceback.\n\n"
            f"Raw error: {error_msg.strip()[:300]}"
        )


# ======================================================================
# FACTORY + FALLBACK CHAIN
# ======================================================================

_PROVIDER_MAP = {
    "shellgpt": ShellGPTProvider,
    "openai": OpenAIProvider,
    "anthropic": AnthropicProvider,
    "claude": AnthropicProvider,
    "offline": OfflineAdvisor,
}

# Order used by "auto" mode and by the global error resolver.
_FALLBACK_ORDER = ["shellgpt", "openai", "anthropic", "offline"]


class AIProviderFactory:
    """Factory to instantiate the configured AI Provider(s)."""

    @staticmethod
    def create(provider_name: str) -> AIProvider:
        provider_class = _PROVIDER_MAP.get(provider_name.lower())
        if not provider_class:
            raise ValueError(f"AI Provider '{provider_name}' is not supported.")
        return provider_class()

    @staticmethod
    def create_first_available(order: Optional[List[str]] = None) -> AIProvider:
        """Tries each provider in `order` and returns the first one that
        initializes successfully. OfflineAdvisor is always last and
        always succeeds, so this method never raises."""
        for name in (order or _FALLBACK_ORDER):
            try:
                provider = AIProviderFactory.create(name)
                log.info(f"AI Engine: using provider '[green]{provider.name}[/green]'")
                return provider
            except Exception as e:
                log.debug(f"AI provider '{name}' unavailable: {e}")
                continue
        return OfflineAdvisor()


def get_configured_provider() -> Optional[AIProvider]:
    """Resolves the AI provider based on config.yaml's ai.default_provider.
    Returns None only if the user explicitly set 'disabled'."""
    provider_name = settings.ai.default_provider.lower()
    if provider_name == "disabled":
        return None
    if provider_name == "auto":
        return AIProviderFactory.create_first_available()
    try:
        return AIProviderFactory.create(provider_name)
    except Exception as e:
        log.warning(f"AI Provider '{provider_name}' failed to initialize: {e}. Falling back to 'auto' chain.")
        return AIProviderFactory.create_first_available()


def resolve_error(error_msg: str) -> str:
    """The heart of the 'self-healing CLI' requirement: whenever
    anything in the tool fails, call this to get a plain-language
    explanation + fix, trying shellgpt -> openai -> anthropic ->
    offline until one of them returns something useful.
    """
    for name in _FALLBACK_ORDER:
        try:
            provider = AIProviderFactory.create(name)
        except Exception:
            continue
        try:
            result = provider.resolve_cli_error(error_msg)
        except NotImplementedError:
            continue
        if result:
            return result
    # This line should be unreachable since OfflineAdvisor always
    # returns something, but it's kept as an absolute last resort.
    return f"Unable to auto-resolve this error. Raw error: {error_msg.strip()[:300]}"
